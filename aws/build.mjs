/**
 * Packages the two Lambda functions into aws/build/ ready to zip and upload.
 *
 *   node aws/build.mjs
 *
 * No bundler and no extra dev dependencies — it just copies the shared source
 * files in beside each handler, which is also easier to inspect while you are
 * learning what actually goes into a Lambda zip.
 *
 * The chat prompt is imported from api/chat.js (where it is generated from the
 * real projects/achievements/blog data) and written out as a frozen snapshot,
 * so the Lambda can never drift from the site.
 */
import { mkdirSync, copyFileSync, writeFileSync, readFileSync, rmSync } from 'fs';
import { fileURLToPath, pathToFileURL } from 'url';
import { dirname, resolve } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const out = resolve(here, 'build');

const { SYSTEM_INSTRUCTION, MAX_MESSAGE_LENGTH, MAX_HISTORY_ITEMS } = await import(
    pathToFileURL(resolve(root, 'api/chat.js')).href
);

rmSync(out, { recursive: true, force: true });

/* ── contributions: zero npm dependencies ─────────────────────────────── */
const contribDir = resolve(out, 'contributions');
mkdirSync(contribDir, { recursive: true });
copyFileSync(resolve(here, 'lambda/contributions/index.mjs'), resolve(contribDir, 'index.mjs'));
copyFileSync(resolve(root, 'api/_contributions-core.js'), resolve(contribDir, '_contributions-core.js'));

/* ── chat: needs @google/generative-ai installed into the zip ─────────── */
const chatDir = resolve(out, 'chat');
mkdirSync(chatDir, { recursive: true });
copyFileSync(resolve(here, 'lambda/chat/index.mjs'), resolve(chatDir, 'index.mjs'));

writeFileSync(
    resolve(chatDir, 'chat-prompt.mjs'),
    `// GENERATED by aws/build.mjs — do not edit. Source: api/chat.js\n` +
        `export const SYSTEM_INSTRUCTION = ${JSON.stringify(SYSTEM_INSTRUCTION)};\n` +
        `export const MAX_MESSAGE_LENGTH = ${MAX_MESSAGE_LENGTH};\n` +
        `export const MAX_HISTORY_ITEMS = ${MAX_HISTORY_ITEMS};\n`,
    'utf8'
);

const geminiVersion = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
    .dependencies['@google/generative-ai'];

writeFileSync(
    resolve(chatDir, 'package.json'),
    JSON.stringify(
        {
            name: 'lloyd-chat-lambda',
            private: true,
            type: 'module',
            dependencies: { '@google/generative-ai': geminiVersion },
        },
        null,
        2
    ) + '\n',
    'utf8'
);

console.log(`✓ built aws/build/contributions  (no dependencies — zip and upload as-is)`);
console.log(`✓ built aws/build/chat           (prompt snapshot: ${SYSTEM_INSTRUCTION.length} chars)`);
console.log(`
Next:
  cd aws/build/chat && npm install --omit=dev   # pulls @google/generative-ai into node_modules
  then zip each folder's CONTENTS (not the folder itself) and upload to Lambda.
`);
